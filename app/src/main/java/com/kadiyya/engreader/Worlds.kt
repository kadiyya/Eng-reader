package com.kadiyya.engreader

import android.content.Context
import android.graphics.Color
import org.json.JSONArray

data class World(
    val index: Int,
    val name: String,
    val book: String,
    val author: String,
    val color: Int,
    val emoji: String,
    val levels: List<Level>,
)

data class Level(
    val number: Int,
    val title: String,
    val wpm: Int,
    val boss: Boolean,
    val text: String,
    val worldIndex: Int,
) {
    val wordCount: Int = countWords(text)
}

fun countWords(text: String): Int =
    text.split(Regex("\\s+")).count { it.isNotBlank() }

/** Levels are public-domain passages generated by tools/gen.py into assets/levels.json. */
object Worlds {
    @Volatile
    private var cached: List<World>? = null

    fun all(context: Context): List<World> =
        cached ?: synchronized(this) { cached ?: load(context).also { cached = it } }

    fun levels(context: Context): List<Level> = all(context).flatMap { it.levels }

    fun level(context: Context, number: Int): Level? =
        levels(context).firstOrNull { it.number == number }

    fun world(context: Context, level: Level): World = all(context)[level.worldIndex]

    private fun load(context: Context): List<World> {
        val json = context.assets.open("levels.json").bufferedReader().use { it.readText() }
        val worlds = JSONArray(json)
        return (0 until worlds.length()).map { wi ->
            val w = worlds.getJSONObject(wi)
            val levels = w.getJSONArray("levels")
            World(
                index = wi,
                name = w.getString("name"),
                book = w.getString("book"),
                author = w.getString("author"),
                color = Color.parseColor(w.getString("color")),
                emoji = w.getString("emoji"),
                levels = (0 until levels.length()).map { li ->
                    val l = levels.getJSONObject(li)
                    Level(
                        number = l.getInt("number"),
                        title = l.getString("title"),
                        wpm = l.getInt("wpm"),
                        boss = l.getBoolean("boss"),
                        text = l.getString("text"),
                        worldIndex = wi,
                    )
                },
            )
        }
    }
}
